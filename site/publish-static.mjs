import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { generatedPages } from './build.mjs';

for (const file of [...generatedPages, 'sitemap.xml', 'robots.txt']) {
  await mkdir(dirname(file), { recursive: true });
  await cp('dist/' + file, file);
}
await cp('site/assets', 'assets', { recursive: true });

const redirects = JSON.parse(await readFile('dist/redirects.json', 'utf8'));
const rules = Object.entries(redirects).map(([from, to]) =>
  'RewriteRule ^' + from.slice(1).replaceAll('.', '\\.') + '$ ' + to + ' [R=301,L]'
);
await writeFile('.htaccess', [
  '# Generated by npm run publish:static',
  'DirectoryIndex index.html',
  'RewriteEngine On',
  'RewriteCond %{THE_REQUEST} "\\s/+index\\.html[?\\s]"',
  ...rules,
  '',
].join('\n'));
